-- =============================================================================
-- 01_db_and_data.sql  |  Snowflake: database, schemas, raw tables, data load
-- Run as: ACCOUNTADMIN (or a role with CREATE DATABASE + CREATE WAREHOUSE)
-- Prereq: the CSVs in data/output/csv/ (shipped with the repo; everyone uses the same data)
-- PUT commands must run from SnowSQL / Snowflake CLI (`snow sql -f`) on your laptop,
-- or upload the CSVs to @RAW.DATA_STAGE via Snowsight > Data > Add Data.
-- =============================================================================
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS SC_EVAL_WH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
USE WAREHOUSE SC_EVAL_WH;

CREATE DATABASE IF NOT EXISTS SUPPLY_CHAIN_EVAL;
CREATE SCHEMA IF NOT EXISTS SUPPLY_CHAIN_EVAL.RAW;        -- tables
CREATE SCHEMA IF NOT EXISTS SUPPLY_CHAIN_EVAL.DOCS;       -- contracts, search
CREATE SCHEMA IF NOT EXISTS SUPPLY_CHAIN_EVAL.ANALYTICS;  -- semantic view, agents
CREATE SCHEMA IF NOT EXISTS SUPPLY_CHAIN_EVAL.EVAL;       -- optional: scratch space for eval notes
USE SCHEMA SUPPLY_CHAIN_EVAL.RAW;

CREATE OR REPLACE FILE FORMAT CSV_FMT TYPE = CSV SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"' EMPTY_FIELD_AS_NULL = TRUE NULL_IF = ('');
CREATE OR REPLACE STAGE DATA_STAGE FILE_FORMAT = CSV_FMT;

-- ---------- Tables ----------
CREATE OR REPLACE TABLE DIM_SUPPLIER (
  SUPPLIER_ID STRING PRIMARY KEY, SUPPLIER_NAME STRING, SUPPLIER_REGION STRING,
  TIER STRING, CONTRACT_ID STRING, CONTRACT_GRACE_DAYS INT);
CREATE OR REPLACE TABLE DIM_PLANT (
  PLANT_ID STRING PRIMARY KEY, PLANT_NAME STRING, PLANT_REGION STRING, COUNTRY STRING);
CREATE OR REPLACE TABLE DIM_COMPONENT (
  COMPONENT_ID STRING PRIMARY KEY, COMPONENT_NAME STRING, CATEGORY STRING,
  UNIT_COST NUMBER(12,2), CRITICALITY STRING);
CREATE OR REPLACE TABLE FACT_PURCHASE_ORDERS (
  PO_ID STRING PRIMARY KEY, SUPPLIER_ID STRING, PLANT_ID STRING, COMPONENT_ID STRING,
  ORDER_DATE DATE, PROMISED_DATE DATE, ACTUAL_DELIVERY_DATE DATE,
  QUANTITY INT, UNIT_PRICE NUMBER(12,2), STATUS STRING, IS_LATE BOOLEAN);
CREATE OR REPLACE TABLE FACT_INVENTORY_DAILY (
  SNAPSHOT_DATE DATE, PLANT_ID STRING, COMPONENT_ID STRING,
  ON_HAND_QTY INT, SAFETY_STOCK_QTY INT);
CREATE OR REPLACE TABLE FACT_DOWNTIME_EVENTS (
  EVENT_ID STRING PRIMARY KEY, PLANT_ID STRING, COMPONENT_ID STRING, SUPPLIER_ID STRING,
  EVENT_DATE DATE, EVENT_TYPE STRING, DOWNTIME_HOURS NUMBER(6,1), COST_PER_HOUR NUMBER(10,2));

-- ---------- Upload (run from local CLI; adjust absolute path) ----------
-- PUT file:///<REPO_PATH>/data/output/csv/*.csv @SUPPLY_CHAIN_EVAL.RAW.DATA_STAGE AUTO_COMPRESS=TRUE OVERWRITE=TRUE;

-- ---------- Load ----------
COPY INTO DIM_SUPPLIER          FROM @DATA_STAGE PATTERN = '.*dim_supplier.csv.*';
COPY INTO DIM_PLANT             FROM @DATA_STAGE PATTERN = '.*dim_plant.csv.*';
COPY INTO DIM_COMPONENT         FROM @DATA_STAGE PATTERN = '.*dim_component.csv.*';
COPY INTO FACT_PURCHASE_ORDERS  FROM @DATA_STAGE PATTERN = '.*fact_purchase_orders.csv.*';
COPY INTO FACT_INVENTORY_DAILY  FROM @DATA_STAGE PATTERN = '.*fact_inventory_daily.csv.*';
COPY INTO FACT_DOWNTIME_EVENTS  FROM @DATA_STAGE PATTERN = '.*fact_downtime_events.csv.*';

-- NOTE: No hand-built views or semantic logic. The semantic layer is generated by
-- Semantic View Autopilot (README.md, Step 1) from these raw tables only.

-- ---------- Validation (expect 12 / 5 / 40 / 3000 / 18250 / 150) ----------
SELECT 'DIM_SUPPLIER' t, COUNT(*) FROM DIM_SUPPLIER UNION ALL
SELECT 'DIM_PLANT', COUNT(*) FROM DIM_PLANT UNION ALL
SELECT 'DIM_COMPONENT', COUNT(*) FROM DIM_COMPONENT UNION ALL
SELECT 'FACT_PURCHASE_ORDERS', COUNT(*) FROM FACT_PURCHASE_ORDERS UNION ALL
SELECT 'FACT_INVENTORY_DAILY', COUNT(*) FROM FACT_INVENTORY_DAILY UNION ALL
SELECT 'FACT_DOWNTIME_EVENTS', COUNT(*) FROM FACT_DOWNTIME_EVENTS;
