-- =============================================================================
-- 03_governance.sql  |  Snowflake: row-level test (EMEA-only analyst)
-- Test: agent queried as SC_EMEA_ANALYST must return only EMEA-plant rows
-- =============================================================================
USE ROLE ACCOUNTADMIN;
USE SCHEMA SUPPLY_CHAIN_EVAL.RAW;

CREATE OR REPLACE TABLE REGION_ACCESS (ROLE_NAME STRING, PLANT_REGION STRING);
INSERT INTO REGION_ACCESS VALUES ('SC_EMEA_ANALYST', 'EMEA');

CREATE OR REPLACE ROW ACCESS POLICY PLANT_REGION_RAP AS (P_PLANT_ID STRING) RETURNS BOOLEAN ->
  CURRENT_ROLE() IN ('ACCOUNTADMIN', 'SYSADMIN')
  OR EXISTS (SELECT 1 FROM SUPPLY_CHAIN_EVAL.RAW.DIM_PLANT p
             JOIN SUPPLY_CHAIN_EVAL.RAW.REGION_ACCESS a ON a.PLANT_REGION = p.PLANT_REGION
             WHERE p.PLANT_ID = P_PLANT_ID AND a.ROLE_NAME = CURRENT_ROLE());

ALTER TABLE FACT_PURCHASE_ORDERS ADD ROW ACCESS POLICY PLANT_REGION_RAP ON (PLANT_ID);
ALTER TABLE FACT_DOWNTIME_EVENTS ADD ROW ACCESS POLICY PLANT_REGION_RAP ON (PLANT_ID);
ALTER TABLE FACT_INVENTORY_DAILY ADD ROW ACCESS POLICY PLANT_REGION_RAP ON (PLANT_ID);

CREATE ROLE IF NOT EXISTS SC_EMEA_ANALYST;
-- Grants the test role to whoever runs this script; set TEST_USER to grant it to someone else
SET TEST_USER = CURRENT_USER();
SET GRANT_STMT = 'GRANT ROLE SC_EMEA_ANALYST TO USER "' || $TEST_USER || '"';
EXECUTE IMMEDIATE $GRANT_STMT;
GRANT USAGE ON WAREHOUSE SC_EVAL_WH TO ROLE SC_EMEA_ANALYST;
GRANT USAGE ON DATABASE SUPPLY_CHAIN_EVAL TO ROLE SC_EMEA_ANALYST;
GRANT USAGE ON ALL SCHEMAS IN DATABASE SUPPLY_CHAIN_EVAL TO ROLE SC_EMEA_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA SUPPLY_CHAIN_EVAL.RAW TO ROLE SC_EMEA_ANALYST;
GRANT SELECT ON ALL SEMANTIC VIEWS IN SCHEMA SUPPLY_CHAIN_EVAL.ANALYTICS TO ROLE SC_EMEA_ANALYST;
GRANT USAGE ON CORTEX SEARCH SERVICE SUPPLY_CHAIN_EVAL.DOCS.CONTRACTS_SEARCH TO ROLE SC_EMEA_ANALYST;
GRANT USAGE ON AGENT SUPPLY_CHAIN_EVAL.ANALYTICS.SC_RISK_AGENT TO ROLE SC_EMEA_ANALYST;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE SC_EMEA_ANALYST;

-- Verify: expect only PLT-02 and PLT-05
USE ROLE SC_EMEA_ANALYST;
SELECT DISTINCT PLANT_ID FROM SUPPLY_CHAIN_EVAL.RAW.FACT_PURCHASE_ORDERS;
USE ROLE ACCOUNTADMIN;
